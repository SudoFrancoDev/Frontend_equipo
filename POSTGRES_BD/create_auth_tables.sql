-- =====================================================================
--  news_dw — módulo de inicio de sesión (opcional)
--
--  Tabla de cuentas de usuario en un esquema propio (app), separada del
--  data warehouse: create_tables.sql borra dw y mart, pero no app.
--  No se relaciona con ninguna otra tabla.
--
--  Información sensible:
--    password_hash       Argon2id (hash, no reversible)
--    email_enc/name_enc  cifrados con AES (Fernet) usando AUTH_SECRET_KEY
--    email_hash          HMAC-SHA256 del correo normalizado: permite buscar
--                        y exigir correo único sin guardarlo en claro
--    session/reset       solo se guarda el SHA-256 de cada token
--
--  Es idempotente: la API lo ejecuta al arrancar. También se puede correr a mano:
--    psql -h localhost -U myuser -d news_dw -f create_auth_tables.sql
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS app;

CREATE TABLE IF NOT EXISTS app.app_user (
    user_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_hash            TEXT        NOT NULL UNIQUE,      -- un mismo correo no se registra 2 veces
    email_enc             TEXT        NOT NULL,
    name_enc              TEXT        NOT NULL,
    password_hash         TEXT        NOT NULL,

    -- Bloqueo temporal tras intentos fallidos
    failed_attempts       SMALLINT    NOT NULL DEFAULT 0 CHECK (failed_attempts >= 0),
    locked_until          TIMESTAMPTZ,

    -- Sesión única activa (un solo navegador a la vez)
    session_token_hash    TEXT        UNIQUE,
    session_created_at    TIMESTAMPTZ,
    session_last_activity TIMESTAMPTZ,

    -- "Olvidé mi contraseña"
    reset_token_hash      TEXT        UNIQUE,
    reset_expires_at      TIMESTAMPTZ,
    reset_requested_at    TIMESTAMPTZ,

    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_login_at         TIMESTAMPTZ
);
