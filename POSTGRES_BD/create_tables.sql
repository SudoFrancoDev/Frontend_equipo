-- =====================================================================
--  news_dw — table definitions matching the six CSV files
--    dim_date.csv, dim_category.csv, dim_source.csv, dim_article.csv,
--    fact_article.csv, article_content.csv
--
--  Star schema (Kimball):  fact_article in the center, joined to
--  dim_date, dim_category, dim_source and dim_article.
--  article_content = vertical partition (large text kept apart).
--  dim_source      = SCD Type II (valid_from / valid_to / is_current).
--  dim_category    = SCD Type I  (overwritten, no history).
--
--  WARNING: drops and recreates the dw and mart schemas (all their data).
--  Run:  psql -h localhost -U myuser -d news_dw -f create_tables.sql
-- =====================================================================
\set ON_ERROR_STOP on
SET client_min_messages = warning;   -- hide 'drop cascades' notices

DROP SCHEMA IF EXISTS mart CASCADE;
DROP SCHEMA IF EXISTS dw   CASCADE;
CREATE SCHEMA dw;
CREATE SCHEMA mart;

-- ---------------------------------------------------------------------
-- DIMENSIONS
-- ---------------------------------------------------------------------

-- dim_date.csv
CREATE TABLE dw.dim_date (
    date_key      INTEGER  PRIMARY KEY,              -- e.g. 20240601
    full_date     DATE     NOT NULL UNIQUE,          -- '2024-06-01'
    year          SMALLINT NOT NULL,
    quarter       SMALLINT NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    month         SMALLINT NOT NULL CHECK (month BETWEEN 1 AND 12),
    month_name    TEXT     NOT NULL,                 -- 'January'
    week_of_year  SMALLINT NOT NULL CHECK (week_of_year BETWEEN 1 AND 53),
    day_of_month  SMALLINT NOT NULL CHECK (day_of_month BETWEEN 1 AND 31),
    day_of_week   SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),  -- 1 = Monday
    day_name      TEXT     NOT NULL,                 -- 'Monday'
    is_weekend    BOOLEAN  NOT NULL                  -- True = Saturday/Sunday
);

-- dim_category.csv  (SCD Type I)
CREATE TABLE dw.dim_category (
    category_key   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_code  TEXT NOT NULL UNIQUE,             -- short identifier, e.g. 'technology'
    category_name  TEXT NOT NULL                     -- display name, e.g. 'Technology'
);

-- dim_source.csv  (SCD Type II)
CREATE TABLE dw.dim_source (
    source_key     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_domain  TEXT        NOT NULL,             -- 'example.com'
    source_name    TEXT        NOT NULL,             -- 'BBC News'
    valid_from     TIMESTAMPTZ NOT NULL,             -- '2024-01-01' or a full timestamp
    valid_to       TIMESTAMPTZ,                      -- empty/NULL = still active
    is_current     BOOLEAN     NOT NULL,
    CHECK (valid_to IS NULL OR valid_to > valid_from)
);
-- Only one current version per source
CREATE UNIQUE INDEX ux_dim_source_current ON dw.dim_source (source_domain) WHERE is_current;
CREATE INDEX ix_dim_source_domain ON dw.dim_source (source_domain);

-- dim_article.csv
CREATE TABLE dw.dim_article (
    article_key  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url          TEXT NOT NULL UNIQUE,
    title        TEXT NOT NULL
);

-- ---------------------------------------------------------------------
-- FACT  (grain: one row per article)
-- ---------------------------------------------------------------------

-- fact_article.csv
CREATE TABLE dw.fact_article (
    article_key       BIGINT      PRIMARY KEY
                      REFERENCES dw.dim_article (article_key) ON DELETE CASCADE,
    date_key          INTEGER     NOT NULL REFERENCES dw.dim_date (date_key),
    category_key      INTEGER     NOT NULL REFERENCES dw.dim_category (category_key),
    source_key        INTEGER     NOT NULL REFERENCES dw.dim_source (source_key),
    published_at      TIMESTAMPTZ NOT NULL,
    title_length      INTEGER     NOT NULL CHECK (title_length >= 0),      -- characters
    input_text_words  INTEGER     NOT NULL CHECK (input_text_words >= 0)   -- words
);
CREATE INDEX ix_fact_date      ON dw.fact_article (date_key);
CREATE INDEX ix_fact_category  ON dw.fact_article (category_key);
CREATE INDEX ix_fact_source    ON dw.fact_article (source_key);
CREATE INDEX ix_fact_published ON dw.fact_article (published_at);

-- ---------------------------------------------------------------------
-- VERTICAL PARTITION — article body kept out of the fact table
-- ---------------------------------------------------------------------

-- article_content.csv
CREATE TABLE dw.article_content (
    article_key  BIGINT PRIMARY KEY
                 REFERENCES dw.dim_article (article_key) ON DELETE CASCADE,
    input_text   TEXT
);
-- Full-text search over the article body
CREATE INDEX ix_content_fts ON dw.article_content
    USING GIN (to_tsvector('simple', coalesce(input_text, '')));

-- ---------------------------------------------------------------------
-- DATA MARTS / OLAP
-- ---------------------------------------------------------------------

-- Everything in one flat view
CREATE VIEW mart.v_articles AS
SELECT f.article_key,
       a.title,
       a.url,
       f.published_at,
       c.category_name  AS category,
       s.source_name,
       s.source_domain,
       ac.input_text,
       d.full_date, d.year, d.quarter, d.month, d.month_name, d.day_name, d.is_weekend,
       f.title_length,
       f.input_text_words
FROM dw.fact_article f
JOIN dw.dim_article  a  ON a.article_key  = f.article_key
JOIN dw.dim_date     d  ON d.date_key     = f.date_key
JOIN dw.dim_category c  ON c.category_key = f.category_key
JOIN dw.dim_source   s  ON s.source_key   = f.source_key
LEFT JOIN dw.article_content ac ON ac.article_key = f.article_key;

-- Monthly volume per category and source
CREATE VIEW mart.v_monthly_by_category_source AS
SELECT d.year, d.month, d.month_name, c.category_name, s.source_name,
       count(*)                           AS articles,
       round(avg(f.input_text_words), 1)  AS avg_words,
       round(avg(f.title_length), 1)      AS avg_title_length
FROM dw.fact_article f
JOIN dw.dim_date     d ON d.date_key     = f.date_key
JOIN dw.dim_category c ON c.category_key = f.category_key
JOIN dw.dim_source   s ON s.source_key   = f.source_key
GROUP BY d.year, d.month, d.month_name, c.category_name, s.source_name;

-- OLAP cube: all subtotals of year x category x source
-- Refresh after each load: REFRESH MATERIALIZED VIEW mart.mv_article_cube;
CREATE MATERIALIZED VIEW mart.mv_article_cube AS
SELECT d.year, c.category_name, s.source_name, count(*) AS articles
FROM dw.fact_article f
JOIN dw.dim_date     d ON d.date_key     = f.date_key
JOIN dw.dim_category c ON c.category_key = f.category_key
JOIN dw.dim_source   s ON s.source_key   = f.source_key
GROUP BY CUBE (d.year, c.category_name, s.source_name);
